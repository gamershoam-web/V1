// Converts the Sacramento script font into SVG paths for the animated wordmarks.
// Writes site/js/wordmark-data.js and renders the intro wordmark into index.html (between markers),
// so the opening animation works before any JavaScript has loaded.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import opentype from 'opentype.js';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const FONT = path.join(ROOT, 'node_modules/@fontsource/sacramento/files/sacramento-latin-400-normal.woff');
const TEXTS = ['Orbit Network', 'Orbit', 'Network', 'Arcade Sector', 'Command Deck', 'Join the community'];
const SIZE = 100;
const PAD = 8;

const buf = fs.readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const out = {};
for (const text of TEXTS) {
  const glyphPaths = font.getPaths(text, 0, 0, SIZE, { kerning: true }).filter((p) => p.commands.length);
  const boxes = glyphPaths.map((p) => p.getBoundingBox());
  const x1 = Math.min(...boxes.map((b) => b.x1)), y1 = Math.min(...boxes.map((b) => b.y1));
  const x2 = Math.max(...boxes.map((b) => b.x2)), y2 = Math.max(...boxes.map((b) => b.y2));
  const dx = PAD - x1, dy = PAD - y1;
  const w = Math.ceil(x2 - x1 + PAD * 2), h = Math.ceil(y2 - y1 + PAD * 2);
  const glyphs = glyphPaths.map((p, i) => {
    p.commands.forEach((c) => {
      for (const k of ['x', 'x1', 'x2']) if (c[k] !== undefined) c[k] += dx;
      for (const k of ['y', 'y1', 'y2']) if (c[k] !== undefined) c[k] += dy;
    });
    const b = boxes[i];
    return { d: p.toPathData(1), t: (b.x1 - x1) / Math.max(1, x2 - x1) };
  });
  out[text] = { w, h, baseline: +(dy).toFixed(1), glyphs };
}

const dataFile = path.join(ROOT, 'site/js/wordmark-data.js');
fs.writeFileSync(dataFile, `// Generated by scripts/build-wordmarks.mjs from the Sacramento font (SIL Open Font License). Do not edit.\nexport const WORDMARKS = ${JSON.stringify(out)};\n`);
console.log(`wrote ${path.relative(ROOT, dataFile)} (${(fs.statSync(dataFile).size / 1024).toFixed(1)} KB)`);

// Render the intro wordmark statically (it starts 1.05s after page load, in sync with the intro CSS).
const { wordmarkSVG } = await import(pathToFileURL(path.join(ROOT, 'site/js/wordmark.js')).href + `?t=${Date.now()}`);
const indexFile = path.join(ROOT, 'site/index.html');
let html = fs.readFileSync(indexFile, 'utf8');
const start = '<!-- wordmark:intro -->', end = '<!-- /wordmark:intro -->';
const a = html.indexOf(start), b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error('intro wordmark markers not found in index.html');
const svg = wordmarkSVG('Orbit Network', { cls: 'wm-intro', label: 'Orbit Network', begin: 1.05, idPrefix: 'wmintro' });
html = html.slice(0, a + start.length) + '\n' + svg + '\n' + html.slice(b);
fs.writeFileSync(indexFile, html);
console.log('rendered intro wordmark into site/index.html');
